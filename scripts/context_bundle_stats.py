#!/usr/bin/env python3
"""context_bundle_stats.py — size and composition of the per-case debug context.

For every cases/<case>/context/ directory (the material an agent gets in the
context-augmented condition, `bench.sh agent --context`) this computes file
count, bytes, lines, words and an approximate token count (words * 1.3, a
rough cross-tokenizer proxy), the file-type composition (by file-name
convention), and summary statistics overall and per tier.

Usage:
    python3 scripts/context_bundle_stats.py [--out-dir analysis]

Writes <out-dir>/context_bundle_stats.json and context_bundle_stats.md.
Standard library only.
"""

from __future__ import annotations

import argparse
import json
import statistics
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WORD_TO_TOKEN = 1.3


def categorize(filename: str) -> str:
    """Bucket a debug-context file by its file-name convention."""
    name = filename.lower()
    if name.startswith("code-investigation"):
        return "code-investigation"
    if "test-output" in name or "test_output" in name:
        return "test-output"
    if "cli-session" in name or "cli-output" in name:
        return "cli-session"
    if "crash" in name:
        return "crash-output"
    if "goroutine" in name or "thread-dump" in name:
        return "goroutine-dump"
    if "race" in name or "sanitizer" in name:
        return "race/sanitizer"
    if "gdb" in name or "backtrace" in name:
        return "debugger-trace"
    if "runtime-" in name or "replica-sync" in name:
        return "runtime-state"
    return "other"


def analyze_case(case_dir: Path) -> dict | None:
    ctx = case_dir / "context"
    files = sorted(f for f in ctx.rglob("*") if f.is_file()) if ctx.is_dir() else []
    if not files:
        return None
    per_file, cats = [], Counter()
    for f in files:
        text = f.read_text(errors="replace")
        rec = {
            "name": str(f.relative_to(ctx)),
            "bytes": f.stat().st_size,
            "lines": text.count("\n") + (0 if not text or text.endswith("\n") else 1),
            "words": len(text.split()),
            "category": categorize(f.name),
        }
        per_file.append(rec)
        cats[rec["category"]] += 1
    words = sum(r["words"] for r in per_file)
    return {
        "case": case_dir.name,
        "n_files": len(per_file),
        "total_bytes": sum(r["bytes"] for r in per_file),
        "total_lines": sum(r["lines"] for r in per_file),
        "total_words": words,
        "est_tokens_word_proxy": round(words * WORD_TO_TOKEN),
        "categories": dict(cats),
        "files": per_file,
    }


def summarize(values: list) -> dict:
    if not values:
        return {}
    s = sorted(values)
    return {"n": len(s), "min": s[0], "p25": s[len(s) // 4], "median": s[len(s) // 2],
            "p75": s[3 * len(s) // 4], "max": s[-1], "mean": round(statistics.mean(s), 1)}


def tier_map() -> dict[str, str]:
    reg = ROOT / "registry" / "case_registry.json"
    if not reg.exists():
        return {}
    return {c["case_id"]: c.get("surface_membership") for c in json.loads(reg.read_text())["cases"]
            if c.get("surface_membership")}


def write_markdown(summary: dict, out_path: Path) -> None:
    n = summary["n_cases"]
    lines = [
        "# DDBench Debug-Context Bundle Statistics",
        "",
        "Generated by `scripts/context_bundle_stats.py` from `cases/*/context/`.",
        "",
        f"Cases with a context bundle: **{n}** of {summary['n_cases_total']}  ",
        f"Total debug-context bytes: **{summary['total_bytes']:,}**  ",
        f"Total files: **{summary['total_files']}**  ",
        "",
    ]
    if summary["cases_without_context"]:
        lines += ["Cases without a context bundle (the agent gets an empty `context/`): "
                  + ", ".join(f"`{c}`" for c in summary["cases_without_context"]), ""]
    lines += ["## Per-case distribution (cases with a bundle)", "",
              "| Metric | min | p25 | median | p75 | max | mean |",
              "|---|---:|---:|---:|---:|---:|---:|"]
    for label, key in [("Files per case", "n_files"), ("Bytes per case", "total_bytes"),
                       ("Lines per case", "total_lines"), ("Words per case", "total_words"),
                       ("Est. tokens (words*1.3)", "est_tokens_word_proxy")]:
        s = summary["distributions"][key]
        lines.append(f"| {label} | {s['min']} | {s['p25']} | {s['median']} | {s['p75']} | "
                     f"{s['max']} | {s['mean']} |")
    lines += ["", "## File-type composition (cases containing at least one file of each kind)", "",
              "| Category | Cases | Share |", "|---|---:|---:|"]
    for cat, k in sorted(summary["category_case_counts"].items(), key=lambda x: (-x[1], x[0])):
        lines.append(f"| {cat} | {k} | {k / n * 100:.1f}% |")
    lines.append("")
    if summary.get("per_tier"):
        lines += ["## Per-tier summary (median values, cases with a bundle)", "",
                  "| Tier | n | files | bytes | lines | est. tokens |",
                  "|---|---:|---:|---:|---:|---:|"]
        for tier, t in summary["per_tier"].items():
            lines.append(f"| {tier} | {t['n_cases']} | {t['median_files']} | {t['median_bytes']} | "
                         f"{t['median_lines']} | {t['median_tokens']} |")
        lines.append("")
    out_path.write_text("\n".join(lines))


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--out-dir", default=str(ROOT / "analysis"))
    args = ap.parse_args()
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    case_dirs = sorted(d for d in (ROOT / "cases").iterdir() if (d / "case.yaml").is_file())
    per_case, missing = [], []
    for d in case_dirs:
        rec = analyze_case(d)
        (per_case.append(rec) if rec else missing.append(d.name))

    cat_cases = Counter(cat for rec in per_case for cat in rec["categories"])
    summary = {
        "n_cases": len(per_case),
        "n_cases_total": len(case_dirs),
        "cases_without_context": missing,
        "total_bytes": sum(c["total_bytes"] for c in per_case),
        "total_files": sum(c["n_files"] for c in per_case),
        "category_case_counts": dict(cat_cases),
        "distributions": {k: summarize([c[k] for c in per_case]) for k in
                          ["n_files", "total_bytes", "total_lines", "total_words",
                           "est_tokens_word_proxy"]},
    }
    tiers = tier_map()
    by_tier = defaultdict(list)
    for c in per_case:
        if tiers.get(c["case"]):
            by_tier[tiers[c["case"]]].append(c)
    if by_tier:
        summary["per_tier"] = {
            tier: {"n_cases": len(rs),
                   "median_files": statistics.median(r["n_files"] for r in rs),
                   "median_bytes": int(statistics.median(r["total_bytes"] for r in rs)),
                   "median_lines": int(statistics.median(r["total_lines"] for r in rs)),
                   "median_tokens": int(statistics.median(r["est_tokens_word_proxy"] for r in rs))}
            for tier, rs in sorted(by_tier.items())
        }

    (out_dir / "context_bundle_stats.json").write_text(
        json.dumps({"summary": summary, "per_case": per_case}, indent=2) + "\n")
    write_markdown(summary, out_dir / "context_bundle_stats.md")
    print(f"Analyzed {len(per_case)} context bundles ({len(missing)} cases without one); "
          f"wrote {out_dir}/context_bundle_stats.{{json,md}}")


if __name__ == "__main__":
    main()
